import React, { useState, useEffect } from "react";
import { request } from "../api/client.js";
import { buildDossier } from "../lib/dossier.js";

/**
 * Loading wrapper for the Case Dossier page.
 * Fetches case details, leads, and graph, and delegates rendering to DossierView.
 */
export function Dossier({ caseId, user }) {
  const [loading, setLoading] = useState(true);
  const [errorText, setErrorText] = useState(null);
  const [caseDetail, setCaseDetail] = useState(null);
  const [leads, setLeads] = useState(null);
  const [graph, setGraph] = useState(null);
  const [people, setPeople] = useState(null);
  const [generatedAt, setGeneratedAt] = useState("");

  useEffect(() => {
    if (!caseId) return;

    setLoading(true);
    setErrorText(null);

    // Compute browser time on mount for deterministic rendering
    const now = new Date();
    const pad = (n) => String(n).padStart(2, "0");
    const stamp = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}:${pad(now.getSeconds())}`;
    setGeneratedAt(stamp);

    async function loadData() {
      try {
        const detail = await request(`/cases/${caseId}`);
        setCaseDetail(detail);

        if (detail?.case?.analyzed) {
          try {
            const [leadsData, graphData, peopleData] = await Promise.all([
              request(`/cases/${caseId}/leads`),
              request(`/cases/${caseId}/graph`),
              request(`/cases/${caseId}/people`),
            ]);
            setLeads(leadsData);
            setGraph(graphData);
            setPeople(peopleData);
          } catch (analysisErr) {
            // Case marked analyzed but leads/graph request failed
            setErrorText(analysisErr.message || "Failed to load case analysis");
          }
        }
      } catch (err) {
        setErrorText(err.message || "Failed to load case details");
      } finally {
        setLoading(false);
      }
    }

    loadData();
  }, [caseId]);

  if (loading) {
    return (
      <div style={{ padding: "16px", color: "var(--muted)" }}>
        Loading case dossier...
      </div>
    );
  }

  if (errorText) {
    return (
      <div style={{ padding: "16px" }}>
        <div className="error-text" style={{ marginBottom: "8px" }}>
          {errorText}
        </div>
        <button type="button" onClick={() => window.location.reload()}>
          Retry
        </button>
      </div>
    );
  }

  const dossier = buildDossier({
    caseDetail,
    leads,
    graph,
    people,
    user,
    generatedAt,
  });

  return <DossierView dossier={dossier} onPrint={() => window.print()} />;
}

